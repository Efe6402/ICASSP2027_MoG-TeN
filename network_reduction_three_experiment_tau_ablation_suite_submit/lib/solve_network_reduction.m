function result = solve_network_reduction( ...
    X, ...
    R, ...
    L, ...
    V_L, ...
    ell_L, ...
    hyp, ...
    SOLVER, ...
    seed)

    rng(seed,'twister');

    [N,~,T] = size(X);

    % --------------------------------------------------------------------
    % Random non-oracle initialization
    % --------------------------------------------------------------------
    alpha = zeros(T,R);
    C = zeros(N,N,R);
    Z = zeros(N,N,R);
    Udual = zeros(N,N,R);

    scaleC = ...
        max( ...
        std(X(:)), ...
        median(abs(X(:)))) ...
        *sqrt(T);

    scaleC = max( ...
        scaleC, ...
        1e-3);

    for r = 1:R

        a = rand(T,1);

        a = ...
            a/max(norm(a),eps);

        alpha(:,r) = a;

        mask = ...
            triu( ...
            rand(N)<SOLVER.init_density, ...
            1);

        W = ...
            scaleC*(0.5+rand(N));

        A = ...
            triu( ...
            mask.*W, ...
            1);

        Cr = A+A';

        C(:,:,r) = Cr;
        Z(:,:,r) = Cr;
        Udual(:,:,r) = zeros(N);
    end

    Xhat = reconstruct_tensor( ...
        C, ...
        alpha);

    maxit = SOLVER.max_iter;

    hist.objective = nan(maxit,1);
    hist.recon_nmse = nan(maxit,1);

    hist.primal_relative = nan(maxit,1);
    hist.dual_relative = nan(maxit,1);

    hist.rel_obj_change = nan(maxit,1);

    hist.max_alpha_kkt = nan(maxit,1);
    hist.max_alpha_norm = nan(maxit,1);

    branch_counts = zeros(maxit,6);

    converged = false;

    for it = 1:maxit

        max_alpha_kkt_it = 0;
        max_alpha_norm_it = 0;

        % ================================================================
        % BCD over r
        % ================================================================
        for r = 1:R

            old_component = zeros(N,N,T);

            for t = 1:T
                old_component(:,:,t) = ...
                    alpha(t,r)*C(:,:,r);
            end

            % Residual excluding r.
            E = ...
                X ...
                -(Xhat-old_component);

            % ------------------------------------------------------------
            % alpha update
            % ------------------------------------------------------------
            b = zeros(T,1);

            Cr_old = C(:,:,r);

            for t = 1:T

                Et = E(:,:,t);

                b(t) = ...
                    sum(sum( ...
                    Cr_old.*Et));
            end

            alpha_prev = ...
                alpha(:,r);

            [a_new,~,branch,alpha_diag_out] = ...
                exact_alpha_update( ...
                b, ...
                hyp.mu, ...
                L, ...
                V_L, ...
                ell_L, ...
                alpha_prev, ...
                SOLVER);

            alpha(:,r) = a_new;

            branch_counts(it,branch) = ...
                branch_counts(it,branch)+1;

            max_alpha_kkt_it = ...
                max( ...
                max_alpha_kkt_it, ...
                alpha_diag_out.kkt_residual);

            max_alpha_norm_it = ...
                max( ...
                max_alpha_norm_it, ...
                abs(norm(a_new)-1));

            % ------------------------------------------------------------
            % C update
            % ------------------------------------------------------------
            M = zeros(N);

            for t = 1:T
                M = ...
                    M ...
                    +a_new(t)*E(:,:,t);
            end

            M = (M+M')/2;

            S = zeros(N);

            for k = 1:R
                if k~=r
                    S = ...
                        S+C(:,:,k).^2;
                end
            end

            numerator = ...
                2*M ...
                +hyp.zeta*( ...
                Z(:,:,r)-Udual(:,:,r));

            denominator = ...
                (2 ...
                 +2*hyp.gamma ...
                 +hyp.zeta) ...
                +2*hyp.lambda*S;

            Cnew = ...
                numerator./denominator;

            Cnew = max(Cnew,0);

            Cnew = ...
                (Cnew+Cnew')/2;

            Cnew(1:N+1:end) = 0;

            C(:,:,r) = Cnew;

            new_component = zeros(N,N,T);

            for t = 1:T
                new_component(:,:,t) = ...
                    a_new(t)*Cnew;
            end

            Xhat = ...
                Xhat ...
                -old_component ...
                +new_component;
        end

        % ================================================================
        % Z and dual update
        % ================================================================
        Zold = Z;

        nuc_sum = 0;

        for r = 1:R

            Y = ...
                C(:,:,r) ...
                +Udual(:,:,r);

            Y = (Y+Y')/2;

            % Exact symmetric nuclear-norm proximal map.
            [Q,Dvec] = eig(Y,'vector');

            d = real(Dvec);
            Q = real(Q);

            d_shrunk = sign(d).*max(abs(d)-hyp.tau/hyp.zeta,0);

            Zr = Q*diag(d_shrunk)*Q';
            Zr = (Zr+Zr')/2;

            Z(:,:,r) = Zr;

            nuc_sum = nuc_sum+sum(abs(d_shrunk));

            Udual(:,:,r) = ...
                Udual(:,:,r) ...
                +C(:,:,r) ...
                -Z(:,:,r);

            Udual(:,:,r) = ...
                ( ...
                Udual(:,:,r) ...
                +Udual(:,:,r)')/2;
        end

        % ================================================================
        % Objective
        % ================================================================
        data_term = ...
            sum( ...
            (X(:)-Xhat(:)).^2);

        gamma_term = 0;
        mu_term = 0;
        overlap_term = 0;

        for r = 1:R

            gamma_term = ...
                gamma_term ...
                +norm(C(:,:,r),'fro')^2;

            mu_term = ...
                mu_term ...
                +alpha(:,r)' ...
                *L ...
                *alpha(:,r);
        end

        for r = 1:R
            for k = r+1:R

                overlap_term = ...
                    overlap_term ...
                    +norm( ...
                    C(:,:,r).*C(:,:,k), ...
                    'fro')^2;
            end
        end

        obj = ...
            data_term ...
            +hyp.gamma*gamma_term ...
            +hyp.tau*nuc_sum ...
            +hyp.mu*mu_term ...
            +hyp.lambda*overlap_term;

        % ================================================================
        % ADMM residuals
        % ================================================================
        pri_num = 0;
        pri_den_C = 0;
        pri_den_Z = 0;
        dual_num = 0;

        for r = 1:R

            pri_num = ...
                pri_num ...
                +norm( ...
                C(:,:,r)-Z(:,:,r), ...
                'fro')^2;

            pri_den_C = ...
                pri_den_C ...
                +norm(C(:,:,r),'fro')^2;

            pri_den_Z = ...
                pri_den_Z ...
                +norm(Z(:,:,r),'fro')^2;

            dual_num = ...
                dual_num ...
                +norm( ...
                hyp.zeta ...
                *(Z(:,:,r)-Zold(:,:,r)), ...
                'fro')^2;
        end

        pri_rel = ...
            sqrt(pri_num) ...
            /max( ...
            [1, ...
             sqrt(pri_den_C), ...
             sqrt(pri_den_Z)]);

        dual_rel = ...
            sqrt(dual_num) ...
            /max( ...
            1, ...
            hyp.zeta*sqrt(pri_den_Z));

        hist.objective(it) = obj;

        hist.recon_nmse(it) = ...
            data_term ...
            /max(sum(X(:).^2),eps);

        hist.primal_relative(it) = ...
            pri_rel;

        hist.dual_relative(it) = ...
            dual_rel;

        hist.max_alpha_kkt(it) = ...
            max_alpha_kkt_it;

        hist.max_alpha_norm(it) = ...
            max_alpha_norm_it;

        if it==1

            hist.rel_obj_change(it) = NaN;

        else

            hist.rel_obj_change(it) = ...
                abs( ...
                hist.objective(it) ...
                -hist.objective(it-1)) ...
                /max( ...
                1, ...
                abs(hist.objective(it-1)));
        end

        if SOLVER.verbose_every>0 && ...
                ( ...
                it==1 ...
                ||mod(it,SOLVER.verbose_every)==0)

            fprintf(['      iter=%3d obj=%.6e recon=%.3e ' ...
                     'pri=%.2e dual=%.2e alphaKKT=%.2e\n'], ...
                it, ...
                obj, ...
                hist.recon_nmse(it), ...
                pri_rel, ...
                dual_rel, ...
                max_alpha_kkt_it);
        end

        if it>=SOLVER.min_iter

            if ...
                pri_rel<=SOLVER.tol_primal ...
                &&dual_rel<=SOLVER.tol_dual ...
                &&hist.rel_obj_change(it)<=SOLVER.tol_obj

                converged = true;
                break;
            end
        end
    end

    iterations = it;

    fields = fieldnames(hist);

    for k = 1:numel(fields)
        hist.(fields{k}) = ...
            hist.(fields{k})(1:iterations,:);
    end

    branch_counts = ...
        branch_counts(1:iterations,:);

    result.C = C;
    result.alpha = alpha;
    result.Z = Z;
    result.Udual = Udual;
    result.Xhat = Xhat;

    result.history = hist;
    result.branch_counts = branch_counts;

    result.iterations = iterations;
    result.converged = converged;
end


function [alpha,rho,branch,diagout] = ...
    exact_alpha_update( ...
    b, ...
    mu, ...
    L, ...
    V, ...
    ell, ...
    alpha_prev, ...
    SOLVER)

    T = length(b);

    nb = norm(b);

    % --------------------------------------------------------------------
    % Region V: b = 0
    % --------------------------------------------------------------------
    if nb<=SOLVER.alpha_tol

        if mu<=SOLVER.alpha_tol

            if norm(alpha_prev)>SOLVER.alpha_tol

                alpha = ...
                    alpha_prev ...
                    /norm(alpha_prev);

            else

                alpha = ...
                    ones(T,1)/sqrt(T);
            end

        else

            zero_idx = ...
                ell ...
                <=SOLVER.eig_tol ...
                *max(1,max(ell));

            N0 = V(:,zero_idx);

            p = ...
                N0 ...
                *(N0'*alpha_prev);

            if norm(p)>SOLVER.alpha_tol

                alpha = ...
                    p/norm(p);

            else

                alpha = N0(:,1);

                alpha = ...
                    alpha/norm(alpha);
            end
        end

        rho = 0;
        branch = 5;

        diagout = ...
            alpha_diag( ...
            b, ...
            alpha, ...
            rho, ...
            mu, ...
            L);

        return;
    end

    % --------------------------------------------------------------------
    % mu = 0, b ~= 0
    % --------------------------------------------------------------------
    if mu<=SOLVER.alpha_tol

        alpha = b/nb;
        rho = nb;
        branch = 6;

        diagout = ...
            alpha_diag( ...
            b, ...
            alpha, ...
            rho, ...
            mu, ...
            L);

        return;
    end

    % --------------------------------------------------------------------
    % mu > 0
    % --------------------------------------------------------------------
    d = V'*b;

    eig_scale = ...
        max(1,max(abs(ell)));

    zero_idx = ...
        abs(ell) ...
        <=SOLVER.eig_tol*eig_scale;

    pos_idx = ~zero_idx;

    null_component = ...
        norm(d(zero_idx));

    in_range = ...
        null_component ...
        <=SOLVER.range_tol ...
        *max(1,nb);

    if in_range

        alpha0 = zeros(T,1);

        if any(pos_idx)

            alpha0 = ...
                V(:,pos_idx) ...
                *( ...
                d(pos_idx) ...
                ./(mu*ell(pos_idx)));
        end

        n0 = norm(alpha0);

        if n0<1-1e-9

            % Region IV.
            N0 = V(:,zero_idx);

            p = ...
                N0 ...
                *(N0'*alpha_prev);

            if norm(p)>SOLVER.alpha_tol

                vdir = ...
                    p/norm(p);

            else

                vdir = N0(:,1);

                vdir = ...
                    vdir/norm(vdir);
            end

            alpha = ...
                alpha0 ...
                +sqrt(max(0,1-n0^2))*vdir;

            alpha = ...
                alpha/norm(alpha);

            rho = 0;
            branch = 4;

            diagout = ...
                alpha_diag( ...
                b, ...
                alpha, ...
                rho, ...
                mu, ...
                L);

            return;

        elseif abs(n0-1)<=1e-9

            % Region III.
            alpha = ...
                alpha0/max(n0,eps);

            rho = 0;
            branch = 3;

            diagout = ...
                alpha_diag( ...
                b, ...
                alpha, ...
                rho, ...
                mu, ...
                L);

            return;

        else

            % Region II.
            branch = 2;
        end

    else

        % Region I.
        branch = 1;
    end

    % --------------------------------------------------------------------
    % Positive-rho root by bisection
    % --------------------------------------------------------------------
    hfun = @(rr) ...
        sum( ...
        ( ...
        d./(mu*ell+rr) ...
        ).^2) ...
        -1;

    lo = 0;

    hi = max(nb,1e-12);

    hhi = hfun(hi);

    expand_count = 0;

    while hhi>0 && expand_count<60

        hi = 2*hi;

        hhi = hfun(hi);

        expand_count = ...
            expand_count+1;
    end

    if hhi>0
        error( ...
            'Could not bracket the positive rho root.');
    end

    for k = 1:SOLVER.bisect_maxit

        mid = 0.5*(lo+hi);

        hmid = hfun(mid);

        if abs(hmid)<=SOLVER.bisect_tol

            lo = mid;
            hi = mid;

            break;
        end

        if hmid>0
            lo = mid;
        else
            hi = mid;
        end
    end

    rho = 0.5*(lo+hi);

    y = ...
        d./(mu*ell+rho);

    alpha = V*y;

    alpha = ...
        alpha/max(norm(alpha),eps);

    diagout = ...
        alpha_diag( ...
        b, ...
        alpha, ...
        rho, ...
        mu, ...
        L);
end


function out = ...
    alpha_diag( ...
    b, ...
    alpha, ...
    rho, ...
    mu, ...
    L)

    kkt = ...
        ( ...
        mu*L ...
        +rho*eye(length(alpha)) ...
        ) ...
        *alpha ...
        -b;

    out.kkt_residual = ...
        norm(kkt) ...
        /max(1,norm(b));

    out.norm_error = ...
        abs(norm(alpha)-1);
end
