function paper_axes(ax)
%PAPER_AXES Consistent, restrained styling for paper figures.

if nargin<1 || isempty(ax)
    ax = gca;
end

set(ax, ...
    'FontName','Times New Roman', ...
    'FontSize',13, ...
    'LineWidth',1.0, ...
    'TickDir','out', ...
    'Box','on', ...
    'XGrid','on', ...
    'YGrid','on', ...
    'GridAlpha',0.14, ...
    'MinorGridAlpha',0.08);
end
