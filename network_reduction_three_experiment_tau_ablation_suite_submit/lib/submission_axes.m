function submission_axes(ax)
%SUBMISSION_AXES Consistent paper styling for the three submission figures.
%
% ------------------------- STYLE TUNING -------------------------
% Change these values here to change ALL three submission figures:
FONT_NAME = 'Times New Roman'; % <-- global figure font
TICK_SIZE = 13;                % <-- tick-label font size
AXIS_WIDTH = 1.25;             % <-- axes/box thickness
% ---------------------------------------------------------------

if nargin<1 || isempty(ax)
    ax = gca;
end

set(ax, ...
    'FontName',FONT_NAME, ...
    'FontSize',TICK_SIZE, ...
    'FontWeight','bold', ...
    'LineWidth',AXIS_WIDTH, ...
    'TickDir','out', ...
    'Box','on', ...
    'XGrid','on', ...
    'YGrid','on', ...
    'GridAlpha',0.14, ...
    'MinorGridAlpha',0.07);
end
