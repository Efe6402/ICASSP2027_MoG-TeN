function submission_labels(ax,xlab,ylab)
%SUBMISSION_LABELS Consistent bold axis-label formatting.
%
% ------------------------- STYLE TUNING -------------------------
FONT_NAME = 'Times New Roman'; % <-- global label font
LABEL_SIZE = 16;               % <-- x/y label font size
% ---------------------------------------------------------------

xlabel(ax,xlab, ...
    'Interpreter','latex', ...
    'FontName',FONT_NAME, ...
    'FontSize',LABEL_SIZE, ...
    'FontWeight','bold');

ylabel(ax,ylab, ...
    'Interpreter','latex', ...
    'FontName',FONT_NAME, ...
    'FontSize',LABEL_SIZE, ...
    'FontWeight','bold');
end
